const face = (h: number) => (h >= 80 ? "😄" : h >= 60 ? "🙂" : h >= 40 ? "😐" : h >= 20 ? "😟" : "😢");
/** "less / normal / more" in words, relative to the (real) starting point. */
function amount(x: number, d: { min: number; max: number }, base: number): string {
  const span = x >= base ? d.max - base : base - d.min;
  const r = span ? (x - base) / span : 0;
  return Math.abs(r) < 0.06 ? "normal" : r > 0.6 ? "lots more" : r > 0 ? "more" : r < -0.6 ? "much less" : "less";
}

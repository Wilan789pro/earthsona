  constructor(private host: PlaygroundHost) {
    this.loop = new LabLoop(host.engine, () => this.loopSource(), () => void host.beforePlay(), () => host.afterPlay());
    this.loop.onState = (s) => this.renderTransport(s);
  }

  /** Current experiment, for Luna's context (null when the lab is closed). */
  snapshot(): LabSnapshot | null {
    if (!this.open) return null;
    const r = simulate(this.exp, this.v, this.base);
    return { mission: this.exp, mode: this.mode, values: { ...this.v }, baseline: { ...this.base }, result: r, baselineResult: simulate(this.exp, this.base, this.base), rules: this.mode === "whatif" ? activeRules(this.exp, r).map((x) => x.consequence) : [] };
  }

  show(): void {
    this.open = true;
    this.exp = this.host.state().experience;
    this.mode = "real";
    this.readReal();
    this.base = baselineOf(this.exp, this.realStart());
    this.v = { ...this.base };
    $("real-panel").hidden = true;
    $("playground").hidden = false;
    this.render();
    this.update(true);
    this.host.luna.say(LAB_LINES[0], { mood: "surprised" });
    $("lab-loop-play").focus();
  }

  close(): void {
    this.stop();
    cancelAnimationFrame(this.tween);
    window.clearTimeout(this.talkTimer);
    this.open = false;
    $("playground").hidden = true;
    $("real-panel").hidden = false;
    $("pretend-tag").hidden = true;
    this.host.pretendGlobe(null);
    this.host.showScene(null);
    this.host.onClose();
  }

  refresh(): void {
    if (!this.open) return;
    const exp = this.host.state().experience;
    this.stop();
    this.exp = exp;
    this.readReal();
    this.base = baselineOf(exp, this.realStart());
    this.v = { ...this.base };
    this.mode = "real";
    this.render();
    this.update(true);
  }

  /** Stop every lab sound (the loop and the "two real years" player). */
  stop(): void {
    this.loop.stop();
    if (this.timer !== null) {
      clearTimeout(this.timer);
      this.timer = null;
      this.host.afterPlay();
    }
  }

  // ---------------------------------------------------------------------------
  // Real starting values
  // ---------------------------------------------------------------------------
  private readReal() {
    const { track } = this.host.state();
    this.real = {};
    this.realDates = {};
    for (const l of track?.layers ?? []) {
      const pts = (l.result.series.points as CleanPoint[]).filter((p) => p.value !== null && !p.bridged);
      const last = pts[pts.length - 1];
      if (last) {
        this.real[l.def.variable as RealVar] = last.value as number;
        this.realDates[l.def.variable as RealVar] = fmtDate(last.time, l.result.series, true);
      }
    }
  }

  /** Slider starting values taken from real measurements (where a slider has a real counterpart). */
  private realStart(): Values {
    const { region } = this.host.state();
    if (this.exp === "pulse") return { temp: this.real.T2M ?? NaN, rain: this.real.PRECTOTCORR ?? NaN, sun: this.real.ALLSKY_SFC_SW_DWN ?? NaN };
    if (this.exp === "ocean") return { sst: this.real.SSTA ?? OCEAN[region.id]?.sstAnomaly ?? NaN };
    return {};
  }

  private realRows(): string[] {
    const { region, track } = this.host.state();
    const rows: string[] = [];
    for (const l of track?.layers ?? []) {
      const k = l.def.variable as RealVar;
      if (this.real[k] === undefined) continue;
      const s = l.result.series;
      rows.push(`<li><strong>${esc(KID.label(k))}</strong> ${esc(fmtValue(this.real[k]!, s.unit))} <span class="muted">· ${esc(this.realDates[k] ?? "")} · ${esc(s.source.kind === "noaa" ? "NOAA" : "NASA")}</span></li>`);
    }
    const snap = OCEAN[region.id];
    if (this.exp === "ocean" && snap)
      rows.push(`<li><strong>Team ocean file</strong> ${snap.sst.toFixed(1)} °C (${snap.sstAnomaly > 0 ? "+" : ""}${snap.sstAnomaly.toFixed(2)} °C vs normal)${snap.chlorophyll !== null ? `, chlorophyll ${snap.chlorophyll.toFixed(3)} mg/m³` : ""} <span class="muted">· ${esc(snap.from)}–${esc(snap.to)} · nearest point ${snap.distanceKm} km away · ${esc(snap.sources.temperature)}</span></li>`);
    if (this.exp === "forest" && region.id === "black-river-gorges" && FOREST_DATA.observations.length) {
      const o = FOREST_DATA.observations[FOREST_DATA.observations.length - 1];
      rows.push(`<li><strong>Team forest file</strong> NDVI ${o.ndvi.toFixed(2)}${o.evi !== null ? `, EVI ${o.evi.toFixed(2)}` : ""} <span class="muted">· ${esc(o.date)} · MODIS · ${esc(o.quality)}</span></li>`);
    }
    return rows;
  }


  private renderTransport(s: LoopState) {
    const icon = document.getElementById("lab-loop-icon");
    if (!icon) return;
    icon.setAttribute("href", s === "playing" ? "#i-pause" : "#i-play");
    $("lab-loop-play").setAttribute("aria-label", s === "playing" ? "Pause the lab sound" : s === "paused" ? "Resume the lab sound" : "Play the lab sound");
    $("lab-loop-status").textContent = s === "playing" ? (this.mode === "real" ? "PLAYING · REAL" : "PLAYING · WHAT IF?") : s === "paused" ? "PAUSED" : "STOPPED";
    $("playground").classList.toggle("loop-on", s === "playing");
  }

  private setMode(m: Mode) {
    if (m === this.mode) return;
    cancelAnimationFrame(this.tween);
    this.mode = m;
    this.comparing = false;
    if (m === "real") this.v = { ...this.base };
    this.lastRules = "";
    this.render();
    this.update(true);
    this.host.luna.say(
      m === "real" ? LAB_LINES[1] : LAB_LINES[2],
      { mood: m === "real" ? "happy" : "surprised", polite: true },
    );
    announce(m === "real" ? "Real Earth data mode" : "What if mode: simulation");
  }

  /** Recompute the simulation and refresh meters, rules, scene and globe. */
  private update(instant = false) {
    if (this.tab !== "lab") return;
    const exp = this.exp;
    const shown = this.comparing ? this.base : this.v;
    const r = simulate(exp, shown, this.base);
    const rb = simulate(exp, this.base, this.base);
    for (const d of VARS[exp]) {
      const out = document.getElementById(`lv-${d.key}-out`);
      if (out) out.textContent = fmt(this.v[d.key], d);
      const word = document.getElementById(`lv-${d.key}-word`);
      if (word) word.textContent = amount(this.v[d.key], d, this.base[d.key]);
      const inp = document.getElementById(`lv-${d.key}`) as HTMLInputElement | null;
      if (inp && +inp.value !== this.v[d.key]) inp.value = String(this.v[d.key]);
      inp?.setAttribute("aria-valuetext", `${fmt(this.v[d.key], d)}, real start ${fmt(this.base[d.key], d)}`);
    }
    const h = document.getElementById("lab-health");
    if (!h) return;
    h.textContent = this.mode === "real" || this.comparing ? `${r.health} out of 100 (real)` : `${r.health} out of 100 · real was ${rb.health}`;
    $("lab-face").textContent = face(r.health);
    const bar = $("lab-health-bar");
    bar.style.width = `${r.health}%`;
    bar.style.background = r.health > 66 ? "var(--good)" : r.health > 40 ? "var(--warn)" : "var(--bad)";
    $("lab-health-base").style.left = `${rb.health}%`;
    $("lab-indicators").innerHTML = r.indicators
      .map((ind) => {
        const b = rb.indicators.find((x) => x.key === ind.key)!;
        const bad = ind.good === "high" ? 1 - ind.value : ind.value;
        const col = bad < 0.33 ? "var(--good)" : bad < 0.6 ? "var(--warn)" : "var(--bad)";
        return `<div class="ind"><span class="small">${esc(ind.label)}</span><div class="meter"><span style="width:${Math.round(ind.value * 100)}%;background:${col}"></span><i style="left:${Math.round(b.value * 100)}%" title="real start"></i></div></div>`;
      })
      .join("");
    const rules = this.mode === "whatif" && !this.comparing ? activeRules(exp, r) : [];
    this.renderRules(rules);
    const whatif = this.mode === "whatif" && !this.comparing;
    $("pretend-tag").hidden = false;
    $("pretend-tag").textContent = whatif ? "WHAT IF? · simulation" : "Drawing of real data";
    $("pretend-tag").classList.toggle("real", !whatif);
    if (this.view === "scene") {
      this.host.showScene(r.visual, instant, whatif ? "Simulation" : "Real data");
      this.host.pretendGlobe(null);
    } else {
      this.host.showScene(null);
      cancelAnimationFrame(this.raf);
      this.raf = requestAnimationFrame(() => this.paintGlobe(r, rb, whatif && changesFromBaseline(exp, this.v).length > 0));
    }
  }

  private renderRules(rules: Rule[]) {
    const box = document.getElementById("lab-rules");
    if (!box) return;
    if (this.mode === "real") {
      box.innerHTML = `<p class="small rule-hint">🛰️ Real data: nothing is changed. Switch to <strong>WHAT IF?</strong> to experiment.</p>`;
      $("lab-rule-details").innerHTML = "";
      return;
    }
    const shown = rules.slice(0, 3);
    box.innerHTML = shown.length
      ? `<h3 class="rules-h">What could happen</h3><ul class="rules">${shown
          .map((x) => `<li class="rule m-${x.mood}"><p>${esc(x.kid)}</p><span class="rule-tag">👀 ${esc(x.visual)}</span><span class="rule-tag">🎵 ${esc(x.sound.text)}</span><a class="rule-src small" href="${esc(x.source.url)}" target="_blank" rel="noopener">Source: ${esc(x.source.label)}</a></li>`)
          .join("")}</ul>`
      : `<p class="small rule-hint">Move a slider to see what could happen.</p>`;
    $("lab-rule-details").innerHTML = rules.length
      ? `<ul class="findings">${rules.map((x) => `<li><strong>${esc(x.condition)}</strong> → ${esc(x.consequence)} <a href="${esc(x.source.url)}" target="_blank" rel="noopener">${esc(x.source.label)}</a></li>`).join("")}</ul>`
      : "<p>No rule is active.</p>";
  }

  private paintGlobe(r: SimResult, rb: SimResult, changed: boolean) {
    if (!changed) return this.host.pretendGlobe(null);
    const v = this.comparing ? this.base : this.v;
    if (this.exp === "ocean") this.host.pretendGlobe({ seaWarmth: v.sst - this.base.sst });
    else if (this.exp === "forest") this.host.pretendGlobe({ green: Math.min(1, r.visual.green / Math.max(0.05, rb.visual.green)) });
    else this.host.pretendGlobe({ airWarmth: (v.temp - this.base.temp) * 1.5 }, Math.max(0.2, v.rain / Math.max(0.5, this.base.rain)), v.sun / Math.max(1, this.base.sun));
  }

  /** Luna reacts once the child stops moving the slider (debounced), and never interrupts herself. */
  private talkSoon() {
    if (this.mode !== "whatif") return;
    window.clearTimeout(this.talkTimer);
    const r = simulate(this.exp, this.v, this.base);
    const top = activeRules(this.exp, r)[0];
    if (top) this.host.luna.setMood(top.mood); // her face reacts immediately
    this.talkTimer = window.setTimeout(() => this.narrate(), 900);
  }

  private narrate() {
    const r = simulate(this.exp, this.v, this.base);
    const rules = activeRules(this.exp, r);
    const key = rules.map((x) => x.id).join(",");
    if (key === this.lastRules) return; // same situation: no need to repeat herself
    this.lastRules = key;
    const top = rules[0];
    if (!top) return;
    this.host.luna.say(top.kid, { mood: top.mood, polite: true });
  }

  private applyPreset(i: number) {
    const p = PRESETS[this.exp][i];
    if (this.mode !== "whatif") {
      this.mode = "whatif";
      this.render();
    }
    this.animateTo({ ...this.base, ...p.values }, `What if ${p.label.replace(/^…/, "")}`);
  }

  /** Move sliders smoothly to a target (gradual change, about 1.5 s). */
  private animateTo(target: Values, label: string) {
    cancelAnimationFrame(this.tween);
    this.comparing = false;
    const from = { ...this.v };
    const t0 = performance.now();
    const reduce = matchMedia("(prefers-reduced-motion: reduce)").matches;
    const tick = () => {
      const k = reduce ? 1 : Math.min(1, (performance.now() - t0) / 1500);
      const e = k < 0.5 ? 2 * k * k : 1 - (-2 * k + 2) ** 2 / 2;
      for (const key of Object.keys(target)) this.v[key] = from[key] + (target[key] - from[key]) * e;
      if (k >= 1) for (const d of VARS[this.exp]) this.v[d.key] = Math.round(target[d.key] / d.step) * d.step;
      this.update();
      if (k < 1) this.tween = requestAnimationFrame(tick);
      else {
        const r = simulate(this.exp, this.v, this.base);
        const top = this.mode === "whatif" ? activeRules(this.exp, r)[0] : null;
        this.lastRules = this.mode === "whatif" ? activeRules(this.exp, r).map((x) => x.id).join(",") : "";
        this.host.luna.say(top ? `${label} ${top.kid}` : label, { mood: top?.mood ?? "happy", polite: true });
      }
    };
    tick();
  }


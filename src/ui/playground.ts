/**
 * The Earth Sound Lab (opened from "Earth Sound Lab" in the journey band).
 *  REAL EARTH DATA: the sliders show this place's latest real measurements (locked) and the sound plays them.
 *  WHAT IF?: the sliders start from those real values; moving them runs the simplified simulation
 *  (src/lab/simulation.ts) and the documented scenario rules (src/lab/scenarios.ts). Picture, sound and
 *  Luna respond in real time. Everything in WHAT IF? is labelled as a simulation.
 *  Two real years: plays two real periods with the same rules and describes the difference (not the cause).
 */
type RealVar = "SST" | "SSTA" | "NDVI" | "EVI" | "T2M" | "PRECTOTCORR" | "ALLSKY_SFC_SW_DWN";
type Vals = Partial<Record<RealVar, number>>;
type Mode = "real" | "whatif";

export interface LabSnapshot {
  mission: ExperienceId;
  mode: Mode;
  values: Values;
  baseline: Values;
  result: SimResult;
  baselineResult: SimResult;
  rules: string[];
}

export interface PlaygroundHost {
  state: () => { experience: ExperienceId; region: RegionDef; track: Track | null; palette: PaletteId; layers: LayerToggles };
  luna: Luna;
  engine: SonificationEngine;
  pretendGlobe: (p: Pretend | null, rain?: number, sun?: number) => void;
  /** Show the animated environment (true) or the globe (false) in the stage. */
  showScene: (visual: Record<string, number> | null, instant?: boolean, label?: string) => void;
  askLuna: (message: string) => void;
  beforePlay: () => Promise<void>;
  afterPlay: () => void;
  setVolume: (v: number) => void;
  volume: () => number;
  onClose: () => void;
}

